/**
 * Partie LÉGÈRE du manifeste d'emojis : URL, avatars, groupes de stickers.
 * Aucune dépendance (quelques Ko) : à importer dans les écrans qui n'ont pas
 * besoin de la recherche. Tout est ré-exporté par `./emoji`, qui ajoute
 * `EMOJI_BY_ID`, `isEmojiId` et `searchEmoji` (index complet, ~125 Ko brut).
 *
 * Chaque id correspond à `/public/emoji/<id>.webp` (vérifié par `emoji.test.ts`).
 */

/** URL publique de l'image d'un emoji. */
export function emojiUrl(id: string): string {
  return `/emoji/${id}.webp`;
}

